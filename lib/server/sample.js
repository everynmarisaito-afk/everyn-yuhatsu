/** サンプル車両の行（満了日は今日からの日数で決める）。車輌№は実在と重ならないよう "SM" で始める */
export function sampleVehicles(today) {
  return RAW.map((r, i) => ({
    car_no: `SM${String(i + 1).padStart(8, '0')}`,
    shkn_day: addDays(today, r[0]),
    plate_area: r[6][0],
    plate_class: r[6][1],
    plate_kana: r[6][2],
    plate_number: r[6][3],
    maker: r[1],
    car_name: r[2],
    grade: r[3],
    model_year: r[4],
    mileage_km: r[5],
    koky_no: `SM${String(i + 501).padStart(8, '0')}`,
    customer_name: r[7],
    customer_kana: r[8],
    tel: r[9],
    mobile: r[10],
    email: r[11],
    email2: '',
    mobile_email: '',
    dm_kbn: r[12],
    prefer_tel: r[13],
    prefer_mail: r[14],
    prefer_days: '',
    prefer_from: r[16] ? r[16].slice(0, 4) : '',
    prefer_to: r[16] ? r[16].slice(4) : '',
    sales_staff: r[15],
    service_staff: '',
    is_sample: true,
  }));
}
